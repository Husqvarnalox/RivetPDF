// Serializes objects 1..N (bodies without the "n 0 obj" wrapper) with a valid
// xref table; the catalog must be object 1.
inline std::string buildPdf(const std::vector<std::string>& bodies) {
    std::string out = "%PDF-1.7\n";
    std::vector<std::size_t> offsets;
    for (std::size_t i = 0; i < bodies.size(); ++i) {
        offsets.push_back(out.size());
        out += std::to_string(i + 1) + " 0 obj\n" + bodies[i] + "\nendobj\n";
    }
    const std::size_t xref = out.size();
    out += "xref\n0 " + std::to_string(bodies.size() + 1) + "\n0000000000 65535 f \n";
    for (const std::size_t offset : offsets) {
        std::string number = std::to_string(offset);
        out += std::string(10 - number.size(), '0') + number + " 00000 n \n";
    }
    out += "trailer\n<< /Size " + std::to_string(bodies.size() + 1) + " /Root 1 0 R >>\nstartxref\n" +
           std::to_string(xref) + "\n%%EOF\n";
    return out;
}

inline std::string streamObject(const std::string& dictEntries, const std::string& data) {
    return "<< " + dictEntries + " /Length " + std::to_string(data.size()) + " >>\nstream\n" + data +
           "\nendstream";
}

// The rich two-page document of the Phase 5 integration tests. Both pages are
// 300x400 points (display y = 400 - user y).
//
// Page 1 (z-order of the extracted objects, bottom first):
//   rect   filled red rectangle, user (160,120)-(260,200)
//   image  4x4 RGB image XObject (16 distinct colors), user (40,120)-(120,200)
//   text   "Hello World" Helvetica 18 at (40,340)
//   text   a 3-line paragraph, Helvetica 12, 16 pt leading, baselines at
//          y = 280 / 264 / 248 starting at x = 40:
//          "The quick brown fox" / "jumps over the lazy" / "dog and keeps going"
//   /Annots: a Square (blue border) around "Hello World", a Link (URI) over
//          the paragraph.
// Page 2: the text "Page Two" Helvetica 14 at (40,340) and a green rectangle.
inline std::string richPdf() {
    std::string pixels;
    static const char* const colors[16] = {"FF0000", "00FF00", "0000FF", "FFFF00", "FF00FF", "00FFFF",
                                           "800000", "008000", "000080", "808000", "800080", "008080",
                                           "FFFFFF", "000000", "FF8000", "0080FF"};
    for (int i = 0; i < 16; ++i) pixels += std::string(colors[i]) + (i % 4 == 3 ? "\n" : " ");
    pixels += ">";
    return buildPdf({
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R 8 0 R] /Count 2 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 400] /Contents 4 0 R /Annots [9 0 R 10 0 R] "
        "/Resources << /Font << /F1 5 0 R >> /XObject << /Im1 6 0 R >> >> >>",
        streamObject("",
                     "1 0 0 rg 160 120 100 80 re f\n"
                     "q 80 0 0 80 40 120 cm /Im1 Do Q\n"
                     "BT /F1 18 Tf 40 340 Td (Hello World) Tj ET\n"
                     "BT /F1 12 Tf 16 TL 40 280 Td (The quick brown fox) Tj T* (jumps over the lazy) Tj T* "
                     "(dog and keeps going) Tj ET\n"),
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        streamObject("/Type /XObject /Subtype /Image /Width 4 /Height 4 /ColorSpace /DeviceRGB "
                     "/BitsPerComponent 8 /Filter /ASCIIHexDecode",
                     pixels),
        streamObject("", "0 0.6 0 rg 40 60 120 40 re f\nBT /F1 14 Tf 40 340 Td (Page Two) Tj ET\n"),
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 400] /Contents 7 0 R "
        "/Resources << /Font << /F1 5 0 R >> >> >>",
        "<< /Type /Annot /Subtype /Square /Rect [30 330 170 365] /C [0 0 1] /Border [0 0 2] /F 4 >>",
        "<< /Type /Annot /Subtype /Link /Rect [35 240 210 295] /Border [0 0 0] "
        "/A << /S /URI /URI (https://example.com/) >> >>",
    });
}

// One page whose only content is CMYK fill: the regeneration probe refuses
// it, so every object on it is read-only (ADR-0017).
inline std::string cmykPdf() {
    return buildPdf({
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] /Contents 4 0 R "
        "/Resources << /Font << /F1 5 0 R >> >> >>",
        streamObject("", "0 0 0 1 k 20 20 60 40 re f\nBT /F1 18 Tf 20 150 Td (Hello CMYK) Tj ET\n"),
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    });
}

// A single page with `count` small filled rectangles and `count / 10` short
// text lines (Helvetica 8) laid out on a grid; used by stress and perf probes.
inline std::string denseContentPdf(std::size_t count) {
    std::string content;
    const std::size_t columns = 25;
    for (std::size_t i = 0; i < count; ++i) {
        const std::size_t col = i % columns;
        const std::size_t row = i / columns;
        const double x = 10.0 + static_cast<double>(col) * 20.0;
        const double y = 10.0 + static_cast<double>(row) * 12.0;
        content += std::to_string(static_cast<double>(i % 5) * 0.2) + " 0.2 0.6 rg " + std::to_string(x) + " " +
                   std::to_string(y) + " 14 8 re f\n";
    }
    for (std::size_t i = 0; i < count / 10; ++i) {
        const double x = 10.0 + static_cast<double>(i % 10) * 48.0;
        const double y = 10.0 + static_cast<double>(i / 10) * 12.0 + 9.0;
        content += "0 g BT /F1 8 Tf " + std::to_string(x) + " " + std::to_string(y) + " Td (Row " +
                   std::to_string(i) + ") Tj ET\n";
    }
    const std::size_t rows = count / columns + 2;
    const std::size_t height = rows * 12 + 40;
    return buildPdf({
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 520 " + std::to_string(height) +
            "] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
        streamObject("", content),
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    });
}

